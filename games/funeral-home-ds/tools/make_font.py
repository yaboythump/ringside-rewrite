#!/usr/bin/env python3
"""Writes source/font8.h from libnds' default console font (zlib license).

Usage: tools/make_font.py $BLOCKSDS/libs/libnds/graphics/default_font.png
The 256x24 image holds ASCII 32-127 as 8x8 cells, white on black.
"""
import sys
from pathlib import Path
from PIL import Image

img = Image.open(sys.argv[1]).convert("RGB")
rows = []
for ch in range(96):
    tx, ty = ch % 32, ch // 32
    glyph = []
    for y in range(8):
        bits = 0
        for x in range(8):
            if img.getpixel((tx * 8 + x, ty * 8 + y)) != (0, 0, 0):
                bits |= 0x80 >> x
        glyph.append(bits)
    rows.append("    {" + ", ".join("0x%02X" % b for b in glyph) + "}, // " + repr(chr(32 + ch)))
out = Path(__file__).resolve().parent.parent / "source" / "font8.h"
out.write_text(
    "// 8x8 font for ASCII 32-127, generated by tools/make_font.py - do not edit.\n"
    "// Glyphs from libnds' default console font: Copyright (C) 2005 Dave Murphy (WinterMute)\n"
    "// and the BlocksDS project, zlib license. Bit 7 is the leftmost pixel.\n"
    "#ifndef FONT8_H\n#define FONT8_H\n\n"
    "static const unsigned char FONT8[96][8] = {\n" + "\n".join(rows) + "\n};\n\n#endif\n")
