#!/usr/bin/env python3
"""Writes one tiny C file per vendored emulator source ("unit") so every object file gets a
unique name in Xcode (several cores ship files called audio.c, core.c, memory.c ...).
Each unit pulls in its core's config header, then the real source file, unchanged.

Usage: python3 tools/make_units.py   (run from games/retro-duo)
"""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
CORES = {
    # name: (sources list file, vendor dir, units dir, config header)
    "mgba": ("vendor/mgba/SOURCES.txt", "vendor/mgba", "ios/RetroDuo/GBACore/units", "GBAConfig.h"),
    "bsnes": ("vendor/bsnes/SOURCES.txt", "vendor/bsnes", "ios/RetroDuo/SNESCore/units", "SNESConfig.h"),
}

for name, (listing, vendor, units, config) in CORES.items():
    out = root / units
    out.mkdir(parents=True, exist_ok=True)
    for old in list(out.glob("*.c")) + list(out.glob("*.cpp")):
        old.unlink()
    for source in (root / listing).read_text().split():
        unit = out / (name + "_" + source.replace("/", "_").replace("-", "_"))  # keeps .c / .cpp
        relative = Path("../" * len(Path(units).parts)) / vendor / source
        unit.write_text(f'// Generated by tools/make_units.py\n#include "{config}"\n#include "{relative.as_posix()}"\n')
    print(name, len(list(out.glob("*.c*"))), "units")
