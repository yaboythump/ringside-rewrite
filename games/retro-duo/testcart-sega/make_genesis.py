#!/usr/bin/env python3
"""Builds the Retro Duo Genesis Test Cart (original, 32 KB) from genesis.c.

clang compiles the C for the 68000; this script links the single object file itself
(the cart only needs absolute and PC-relative relocations), then adds the vectors, the
Sega header and its checksum. Usage: python3 make_genesis.py OUTPUT.md
"""
import os
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

here = Path(__file__).resolve().parent
sys.path.insert(0, str(here))
import font  # noqa: E402

CODE_BASE = 0x200
ROM_SIZE = 0x8000


def c_bytes(name, values):
    return f"static const uint8_t {name}[] = {{{', '.join(str(v) for v in values)}}};\n"


def data_header():
    words = font.tiles_4bpp_packed()
    words = [int.from_bytes(words[i:i + 2], "big") for i in range(0, len(words), 2)]
    out = "/* Generated by make_genesis.py */\n"
    out += f"#define FONT_WORDS {len(words)}\nstatic const uint16_t FONT[] = {{{', '.join(hex(w) for w in words)}}};\n"
    for name, s in (("TEXT_BAR", "=" * 24), ("TEXT_TITLE", "RETRO DUO"), ("TEXT_CART", "GENESIS TEST CART"),
                    ("TEXT_MOVE", "D-PAD  MOVE STAR"), ("TEXT_COLOR", "START  COLOR")):
        out += c_bytes(name, font.text(s) + [0xFF])
    out += c_bytes("LETTERS", font.text("ABCXYZ"))
    out += f"#define STAR_TILE {font.CHARS.index('*')}\n"
    return out


def link(obj):
    """Lays out .text/.rodata from one ELF32 big-endian m68k object and applies its relocations."""
    data = obj
    (shoff, ) = struct.unpack_from(">I", data, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from(">HHH", data, 0x2E)
    sections = [struct.unpack_from(">IIIIIIIIII", data, shoff + i * shentsize) for i in range(shnum)]
    strtab_off = sections[shstrndx][4]

    def name_at(table_off, offset):
        end = data.index(b"\0", table_off + offset)
        return data[table_off + offset:end].decode()

    names = [name_at(strtab_off, s[0]) for s in sections]
    image = bytearray()
    placed = {}
    for index, (sname, s) in enumerate(zip(names, sections)):
        kind, flags, size, align = s[1], s[2], s[5], max(1, s[8])
        if kind == 8 and size:  # NOBITS: RAM variables are not supported here
            raise SystemExit(f"section {sname} needs RAM; keep state in locals")
        if kind == 1 and flags & 2 and size:  # PROGBITS + ALLOC
            if flags & 1 and not sname.startswith(".rodata"):
                if sname != ".text" and not sname.startswith(".text"):
                    raise SystemExit(f"writable section {sname} is not supported")
            while len(image) % align:
                image.append(0)
            placed[index] = CODE_BASE + len(image)
            image += data[s[4]:s[4] + size]
    symtab = next(i for i, s in enumerate(sections) if s[1] == 2)
    sym_off, sym_size, sym_link = sections[symtab][4], sections[symtab][5], sections[symtab][6]
    symbols = []
    for i in range(sym_size // 16):
        st_name, value, size, info, other, shndx = struct.unpack_from(">IIIBBH", data, sym_off + i * 16)
        symbols.append((name_at(sections[sym_link][4], st_name), value, shndx))

    def address(sym_index):
        name, value, shndx = symbols[sym_index]
        if shndx not in placed:
            raise SystemExit(f"unresolved symbol {name!r} (no libraries are linked)")
        return placed[shndx] + value

    for index, s in enumerate(sections):
        if s[1] != 4 or s[7] not in placed:  # RELA for a placed section
            continue
        base = placed[s[7]]
        for r in range(s[5] // 12):
            offset, info, addend = struct.unpack_from(">IIi", data, s[4] + r * 12)
            kind, target = info & 0xFF, address(info >> 8) + addend
            where = base + offset - CODE_BASE
            if kind == 1:    # R_68K_32
                struct.pack_into(">I", image, where, target & 0xFFFFFFFF)
            elif kind == 2:  # R_68K_16
                struct.pack_into(">H", image, where, target & 0xFFFF)
            elif kind == 4:  # R_68K_PC32
                struct.pack_into(">i", image, where, target - (base + offset))
            elif kind == 5:  # R_68K_PC16
                struct.pack_into(">h", image, where, target - (base + offset))
            elif kind == 6:  # R_68K_PC8
                struct.pack_into(">b", image, where, target - (base + offset))
            else:
                raise SystemExit(f"relocation type {kind} not supported")
    entry = next(placed[shndx] + value for name, value, shndx in symbols if name == "start")
    return bytes(image), entry


def main():
    clang = os.environ.get("CLANG", "clang")
    with tempfile.TemporaryDirectory() as work:
        Path(work, "genesis_data.h").write_text(data_header())
        obj = Path(work, "genesis.o")
        subprocess.run([clang, "--target=m68k-unknown-elf", "-mcpu=M68000", "-Os", "-ffreestanding",
                        "-fno-pic", "-fno-builtin", "-fno-asynchronous-unwind-tables", "-nostdlib",
                        "-fno-ident", "-ffile-prefix-map=" + str(here) + "=.", "-I", work,
                        "-c", str(here / "genesis.c"), "-o", str(obj)], check=True)
        code, entry = link(obj.read_bytes())
    rom = bytearray(ROM_SIZE)
    struct.pack_into(">II", rom, 0, 0x00FFFE00, entry)  # stack at the top of work RAM
    for vector in range(2, 64):
        struct.pack_into(">I", rom, vector * 4, entry)  # anything unexpected restarts the cart
    header = {0x100: "SEGA MEGA DRIVE ", 0x110: "(C)RDUO 2026.NOV",
              0x120: "RETRO DUO GENESIS TEST CART".ljust(48), 0x150: "RETRO DUO GENESIS TEST CART".ljust(48),
              0x180: "GM 00000000-00", 0x190: "J6".ljust(16), 0x1F0: "JUE".ljust(16)}
    for offset, value in header.items():
        rom[offset:offset + len(value)] = value.encode()
    struct.pack_into(">II", rom, 0x1A0, 0, ROM_SIZE - 1)
    struct.pack_into(">II", rom, 0x1A8, 0xFF0000, 0xFFFFFF)
    rom[0x1B0:0x1BC] = b" " * 12
    assert CODE_BASE + len(code) <= ROM_SIZE, len(code)
    rom[CODE_BASE:CODE_BASE + len(code)] = code
    checksum = sum(struct.unpack_from(">H", rom, i)[0] for i in range(0x200, ROM_SIZE, 2)) & 0xFFFF
    struct.pack_into(">H", rom, 0x18E, checksum)
    Path(sys.argv[1]).write_bytes(rom)
    print(f"{Path(sys.argv[1]).name}: {len(code)} bytes of code")


if __name__ == "__main__":
    main()
