def tile_bytes(rows):
    out = []
    for row in rows:
        bits = int(row.replace("#", "1").replace(".", "0"), 2)
        out += [bits, bits]  # colour 3 where set
    return out


lines = ["; Generated by make_tiles.py - do not edit by hand.", "Tiles:"]
charmap = []
for index, (char, rows) in enumerate(GLYPHS.items()):
    assert len(rows) == 8 and all(len(r) == 8 for r in rows), char
    lines.append("    db " + ", ".join(f"${b:02X}" for b in tile_bytes(rows)) + f"  ; {index} {char!r}")
    charmap.append(f'    CHARMAP "{char}", {index}')
lines.append("TilesEnd:")
lines.append(f"DEF STAR_TILE EQU {list(GLYPHS).index('*')}")
Path(__file__).with_name("tiles.inc").write_text("\n".join(lines + charmap) + "\n")
