#!/usr/bin/env python3
"""Writes font.h for the DS test cart from the Game Boy test cart's original glyphs."""
import importlib.util
from pathlib import Path

here = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("tiles", here.parent / "testcart" / "make_tiles.py")
src = (here.parent / "testcart" / "make_tiles.py").read_text()
glyphs = {}
exec(src.split("def tile_bytes")[0], glyphs)
EXTRA = {
    "H": [".#...#..", ".#...#..", ".#...#..", ".#####..", ".#...#..", ".#...#..", ".#...#..", "........"],
    "I": [".#####..", "...#....", "...#....", "...#....", "...#....", "...#....", ".#####..", "........"],
    "W": [".#...#..", ".#...#..", ".#...#..", ".#.#.#..", ".#.#.#..", ".##.##..", ".#...#..", "........"],
    "X": [".#...#..", ".#...#..", "..#.#...", "...#....", "..#.#...", ".#...#..", ".#...#..", "........"],
    "G": ["..###...", ".#...#..", ".#......", ".#.###..", ".#...#..", ".#...#..", "..###...", "........"],
}
glyphs["GLYPHS"] = {**glyphs["GLYPHS"], **EXTRA}
lines = ["// Generated by font.py - do not edit by hand.", "static const unsigned char FONT[][8] = {"]
chars = []
for ch, rows in glyphs["GLYPHS"].items():
    lines.append("    {" + ", ".join(str(int(r.replace('#', '1').replace('.', '0'), 2)) for r in rows) + "}, // " + repr(ch))
    chars.append(ch)
lines.append("};")
lines.append('static const char FONT_CHARS[] = "' + "".join(chars).replace("\\", "\\\\").replace('"', '\\"') + '";')
(here / "font.h").write_text("\n".join(lines) + "\n")
